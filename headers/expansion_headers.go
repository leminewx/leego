package headers

const (
	// ******************************************************************************************************************
	// * 拓展头：适用于 HTTP 请求或响应，针对特定场景或自定义需求，但可能会被浏览器拦截
	// ******************************************************************************************************************

	/*
		X-Real-IP

		作用：
		  - 代理服务器传递客户端的真实 IP 地址（如 Nginx 反向代理时配置）
	*/
	X_REAL_IP = "X-Real-IP"

	/*
		X-Forwarded-For

		作用：
		  - 记录请求经过的客户端和代理服务器 IP 地址
		格式：
		  - X-Forwarded-For：客户端 IP, 代理1 IP, 代理2 IP, ...
	*/
	X_FORWARDED_FOR = "X-Forwarded-For"

	/*
		X-Requested-With

		作用：
		  - 标识请求是否为 AJAX 请求，值通常为 XMLHttpRequest（部分框架依赖该头判断请求类型）
	*/
	X_REQUESTED_WITH = "X-Requested-With"

	/*
		X-Request-ID

		作用：
		  - 在分布式系统（如微服务架构）中追踪单个请求的全链路流转，是问题排查、日志分析和链路监控的核心工具之一
		  - 为每一个进入系统的 HTTP 请求分配一个全局唯一的 ID（通常是 UUID、随机字符串等），该 ID 会伴随请求在整个服务链路中传递（如客户端 → 网关 → 服务 A → 服务 B → 数据库）
		  - 通过该 ID 可串联起请求经过的所有服务的日志、监控数据和调用记录，快速定位请求在某个环节的异常（如超时、报错）
		  - 在高并发场景下，多个请求的日志会交织输出，通过 X-Request-ID 可精准筛选出目标请求的完整链路日志，避免日志混乱
		场景：
		  - 微服务架构：请求需经过网关、认证服务、业务服务、数据服务等多个节点，X-Request-ID 可追踪请求在各节点的流转状态
		  - 前后端协作：前端发起请求时携带该 ID，后端通过日志记录该 ID，当前端出现问题（如接口超时）时，可将 ID 提供给后端快速定位问题
		  - 第三方接口调用：调用外部服务时传递 X-Request-ID，若请求失败，可通过该 ID 与第三方协同排查问题（需双方约定支持该头字段）
		注意：
		  - 唯一性保证：生成的 X-Request-ID 需确保全局唯一，推荐使用 UUID v4（随机生成）或雪花算法（Snowflake），避免因 ID 重复导致链路追踪混乱
		  - 兼容性处理：部分系统可能使用其他命名的同类头字段（如 Request-ID、Trace-ID），建议在网关层统一映射为 X-Request-ID，避免多格式共存
		  - 性能影响：ID 生成和传递的开销极低，对系统性能几乎无影响，但需确保所有服务都严格遵循传递规则，否则会导致链路断裂
		  - 安全无关：X-Request-ID 仅用于链路追踪，不涉及身份认证或数据加密，无需对其进行加密处理
	*/
	X_REQUEST_ID = "X-Request-ID"
)
